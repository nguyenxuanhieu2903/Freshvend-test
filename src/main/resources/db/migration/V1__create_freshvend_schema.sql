CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(180),
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    description TEXT,
    image_url VARCHAR(255),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    low_stock_threshold INTEGER NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0),
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE iot_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(80) NOT NULL UNIQUE,
    device_name VARCHAR(160) NOT NULL,
    device_type VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    last_heartbeat TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES users(id),
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    order_status VARCHAR(32) NOT NULL,
    payment_status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    transaction_code VARCHAR(64) NOT NULL UNIQUE,
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    status VARCHAR(24) NOT NULL,
    payment_method VARCHAR(32) NOT NULL,
    processed_at TIMESTAMP
);

CREATE TABLE restock_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(id),
    operator_id BIGINT NOT NULL REFERENCES users(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    remaining_quantity INTEGER NOT NULL CHECK (remaining_quantity >= 0 AND remaining_quantity <= quantity),
    expiry_date DATE,
    restocked_at TIMESTAMP NOT NULL
);

CREATE TABLE stock_reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_item(id) ON DELETE CASCADE,
    restock_history_id BIGINT NOT NULL REFERENCES restock_history(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE dispensing_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    result VARCHAR(16) NOT NULL,
    failure_reason TEXT,
    attempted_at TIMESTAMP NOT NULL
);

CREATE TABLE sensor_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES iot_device(id),
    temperature NUMERIC(6,2),
    humidity NUMERIC(6,2),
    door_status VARCHAR(16) NOT NULL,
    data_source VARCHAR(16) NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    received_at TIMESTAMP NOT NULL
);

CREATE TABLE alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT REFERENCES iot_device(id),
    product_id BIGINT REFERENCES product(id),
    alert_type VARCHAR(32) NOT NULL,
    message TEXT NOT NULL,
    severity VARCHAR(16) NOT NULL,
    is_acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    acknowledged_by BIGINT REFERENCES users(id),
    acknowledged_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE incident (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reported_by BIGINT REFERENCES users(id),
    resolved_by BIGINT REFERENCES users(id),
    alert_id BIGINT REFERENCES alert(id),
    title VARCHAR(180) NOT NULL,
    description TEXT,
    status VARCHAR(24) NOT NULL,
    resolution_note TEXT,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE system_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(120) NOT NULL UNIQUE,
    config_value TEXT NOT NULL,
    description TEXT,
    updated_by BIGINT REFERENCES users(id),
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_orders_customer_created ON orders(customer_id, created_at DESC);
CREATE INDEX idx_order_item_product ON order_item(product_id);
CREATE INDEX idx_payment_order ON payment(order_id);
CREATE INDEX idx_restock_product_expiry ON restock_history(product_id, expiry_date);
CREATE INDEX idx_reservation_status ON stock_reservation(status);
CREATE INDEX idx_sensor_device_recorded ON sensor_data(device_id, recorded_at DESC);
CREATE INDEX idx_alert_unacknowledged ON alert(is_acknowledged, created_at DESC);
CREATE INDEX idx_incident_status_created ON incident(status, created_at DESC);
